import { test } from 'node:test';
import assert from 'node:assert/strict';
import { nativeToolChoices, validateNativeToolSettings } from '../src/native-tool-settings.js';
import { profileOverrides, type EngineOptions } from '../src/engine.js';
import type { Config } from '../src/config.js';
const config = { workspace: '/synthetic/workspace', runtime: '/synthetic/runtime', codexBin: '/usr/bin/false', codexHome: '/synthetic/data/codex', nativeCodexHome: '/synthetic/data/codex' } as Config;
test('native feature choices remain separate from the ordinary execution profile', () => {
    assert.deepEqual(nativeToolChoices({ features: { shell_tool: true, view_image: false, shell_snapshot: true, skill_search: true }, web_search: 'live' }), { shell: true, viewImage: false, shellSnapshot: true, skillSearch: true, search: 'live' });
    assert.throws(() => validateNativeToolSettings({ shell: true, network: true }), /capability_tool_settings_invalid/);
    const settings = validateNativeToolSettings({ shell: true, viewImage: true, shellSnapshot: true, skillSearch: true, search: 'live' });
    assert.equal(settings['features.shell_tool'], true);
    assert.equal(settings.web_search, 'live');
    const opts: EngineOptions = { cwd: '/synthetic/workspace', readRoots: [], instructions: '', tools: [], nativeTools: 'main' };
    const profile = profileOverrides(config, opts);
    assert.equal(profile.filesystem[':root'], 'write');
    assert.equal(profile.filesystem[config.runtime], 'deny');
    assert.equal(profile.filesystem[config.codexHome], 'deny');
    assert.equal(profile.filesystem[config.workspace], undefined);
    assert.equal(profile.network.enabled, true);
    const worker = profileOverrides(config, { ...opts, cwd: '/synthetic/another-project', nativeTools: 'worker' });
    assert.deepEqual(worker,profile);
    assert.equal(worker.filesystem[config.workspace], undefined);
    assert.throws(() => profileOverrides({ ...config, codexHome: '/shared/home' }, opts), /engine_native_tools_home_required/);
    assert.throws(() => profileOverrides(config, { ...opts, cwd: config.codexHome + '/nested-workspace' }), /engine_native_tools_workspace_invalid/);
});
test('native defaults are enabled and explicit native choices still win', () => { const choices = nativeToolChoices({}); assert.equal(choices.shell, true); assert.equal(choices.viewImage, true); assert.equal(choices.shellSnapshot, true); assert.equal(choices.skillSearch,true); assert.equal(choices.search, 'cached'); assert.equal(nativeToolChoices({ features: { shell_tool: false } }).shell, false); });
